    @Test
    fun decode_inverted() {
        assertEquals("HELLO", QRDecoder.decode(render(HELLO, scale = 3, invert = true)))
    }

    @Test
    fun decode_moderate_contrast() {
        val img = render(HELLO, scale = 3)
        for (i in img.data.indices) {
            img.data[i] = if ((img.data[i].toInt() and 0xFF) == 0) 40.toByte() else 200.toByte()
        }
        assertEquals("HELLO", QRDecoder.decode(img))
    }

    @Test
    fun decode_rotated() {
        for (turns in 1..3) {
            assertEquals("HELLO", QRDecoder.decode(render(HELLO, scale = 3, rotate = turns)), "turns=$turns")
        }
    }

    @Test
    fun reed_solomon_corrects_a_byte() {
        val rs = ReedSolomon(7)
        val data = ByteArray(19) { (it * 17 + 3).toByte() }
        val ecc = rs.encode(data)
        val codeword = ByteArray(data.size + ecc.size)
        data.copyInto(codeword)
        ecc.copyInto(codeword, data.size)
        codeword[4] = (codeword[4].toInt() xor 0x5A).toByte()
        val decoded = rs.decode(codeword)
        assertContentEquals(data, decoded.copyOf(data.size))
    }

    private fun assertDecodes(expected: String, modules: String) {
        for (scale in intArrayOf(2, 3, 5)) {
            for (channels in intArrayOf(1, 3, 4)) {
                val img = render(modules, scale = scale, channels = channels, pad = 1)
                assertEquals(expected, QRDecoder.decode(img), "scale=$scale channels=$channels")
            }
        }
    }

    private fun render(
        modules: String,
        scale: Int = 3,
        channels: Int = 1,
        invert: Boolean = false,
        pad: Int = 0,
        rotate: Int = 0
    ): Image {
        var rows = modules.trim().lines()
        repeat(rotate and 3) {
            val h = rows.size
            val w = rows[0].length
            rows = List(w) { y ->
                CharArray(h) { x -> rows[h - 1 - x][y] }.concatToString()
            }
        }
        val modH = rows.size
        val modW = rows[0].length
        val width = (modW + pad * 2) * scale
        val height = (modH + pad * 2) * scale
        val data = ByteArray(width * height * channels)
        var i = 0
        for (y in 0 until height) {
            val my = y / scale - pad
            for (x in 0 until width) {
                val mx = x / scale - pad
                val on = my in rows.indices && mx in 0 until modW && rows[my][mx] == '1'
                val dark = if (invert) !on else on
                val v = (if (dark) 0 else 255).toByte()
                repeat(channels) { data[i++] = v }
            }
        }
        return Image(width, height, data)
    }

